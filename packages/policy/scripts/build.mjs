// Builds dist/ for @markerloop/policy (SDL-658): the sections' markdown,
// limits.json, manifest.json and strings.json are embedded into dist/content.js
// so that any bundler (Next's server build included) gets the texts without
// reading the file system at runtime. Runs on `pnpm install` (prepare), like
// the other workspace packages. It does NOT validate — that is the admin's
// prebuild (apps/admin/scripts/validate-policy.mjs), which fails the build.
import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "dist");
const readJson = (name) => JSON.parse(readFileSync(join(root, name), "utf8"));

const manifest = readJson("manifest.json");
const limits = readJson("limits.json");
const strings = readJson("strings.json");

// "# Title" line + the rest of a section file, and the file's sha256.
function readSectionFile(file) {
  const raw = readFileSync(join(root, file));
  const lines = raw.toString("utf8").split("\n");
  const heading = lines.findIndex((line) => line.startsWith("# "));
  if (heading < 0) throw new Error(`${file}: no "# " title line`);
  return {
    title: lines[heading].slice(2).trim(),
    body: lines.slice(heading + 1).join("\n").trim(),
    sha256: createHash("sha256").update(raw).digest("hex"),
  };
}

const sections = manifest.sections.map((entry) => {
  const { title, body, sha256 } = readSectionFile(entry.file);
  const current = entry.revisions[entry.revisions.length - 1];
  // SDL-784: the same section in another language (sections/<locale>/), not
  // a revision — version, effective_date and sha256 stay the Russian ones.
  const translations = Object.fromEntries(
    Object.entries(entry.translations ?? {}).map(([locale, t]) => [locale, readSectionFile(t.file)])
  );
  return {
    slug: entry.slug,
    title,
    body,
    translations,
    promises: entry.promises,
    version: current.version,
    effective_date: current.effective_date,
    sha256,
    owner_request: current.owner_request,
  };
});

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });
writeFileSync(
  join(dist, "content.js"),
  "// Generated by scripts/build.mjs — do not edit.\n" +
    `export const sections = ${JSON.stringify(sections, null, 2)};\n` +
    `export const limits = ${JSON.stringify(limits, null, 2)};\n` +
    `export const strings = ${JSON.stringify(strings, null, 2)};\n` +
    `export const promiseKeys = ${JSON.stringify(Object.keys(manifest.promise_keys), null, 2)};\n`
);
copyFileSync(join(root, "src/index.js"), join(dist, "index.js"));
copyFileSync(join(root, "src/index.d.ts"), join(dist, "index.d.ts"));
console.log(`[policy] built ${sections.length} sections into dist/`);
